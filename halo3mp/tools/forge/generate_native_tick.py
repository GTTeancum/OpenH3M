"""Generate halo3mp/src/forge/forge_native_tick.cpp from Spartan's own
recompiled Halo 3 code (generated/default). It copies Halo 3's Forge
per-player update sub_82281A98 unchanged, except that at the start of its
held-object block (loc_82281F20, just before the call to sub_8227F578) it asks
Advanced Forge whether it owns this held object. If it does, the native held
block is skipped (jump to loc_822821E8); otherwise the native block runs.

Usage: python generate_native_tick.py <generated/default dir> <output .cpp>
"""
import glob
import os
import re
import sys

src_dir, out = sys.argv[1], sys.argv[2]
name = 'sub_82281A98'
source = None
for path in glob.glob(os.path.join(src_dir, 'halo3mp_recomp.*.cpp')):
    text = open(path, encoding='utf8').read()
    start = text.find('DEFINE_REX_FUNC(%s) {' % name)
    if start >= 0:
        source = path
        break
if source is None:
    sys.exit('native tick %s not found' % name)
end = text.index('\n}\n', start) + 3
body = text[start:end]
header = re.match(r'.*halo3mp_recomp\.(\d+)\.cpp$', source).group(1)
body = body.replace('DEFINE_REX_FUNC(%s) {' % name,
                    'void RunNativeForgeTick(PPCContext& ctx, uint8_t* base, NativeHeldDispatch dispatch) {', 1)
anchor = 'loc_82281F20:\n'
assert body.count(anchor) == 1, 'held block label not found exactly once'
assert '\tctx.r3.u64 = ctx.r31.u64;\n\t// bl 0x8227f578' in body.split(anchor, 1)[1][:200], 'held block shape changed'
body = body.replace(anchor, anchor +
                    '\t// Advanced Forge owns this held object: skip the native held block.\n'
                    '\t{ PPCContext stage = ctx; if (dispatch(stage, base, ctx.r18.u32, ctx.r31.u32)) goto loc_822821E8; }\n', 1)
assert body.count('loc_822821E8:') == 1
result = ('// Generated by halo3mp/tools/forge/generate_native_tick.py from Spartan\'s own\n'
          '// recompiled Halo 3 code (%s). Halo 3\'s Forge per-player update\n'
          '// sub_82281A98, unchanged except for the Advanced Forge hand-off at its held block.\n'
          '#include "../../generated/default/halo3mp_funcs.%s.h"\n'
          '#include "forge_native_tick.h"\n\n'
          'namespace advanced_forge {\n' % (os.path.basename(source), header)) + body + '}  // namespace advanced_forge\n'
open(out, 'w', encoding='utf8', newline='\n').write(result)
print('wrote', out, 'from', os.path.basename(source), len(body.splitlines()), 'lines')
