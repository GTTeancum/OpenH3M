"""Retain native pose synchronization, admitting owned H4 keyframed scenery."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
source = (root / 'halo3mp/generated/default/halo3mp_recomp.78.cpp').read_text()
match = re.search(r'DEFINE_REX_FUNC\(sub_82332FF0\) \{.*?\n\}', source, re.S)
if not match:
    raise RuntimeError('Native pose synchronization function missing')
body = match.group().replace('DEFINE_REX_FUNC(sub_82332FF0)',
                            'static void SyncKeyframedScenery(PPCContext& ctx, uint8_t* base)', 1)
gate = '\t// beq cr6,0x82333104\n\tif (ctx.cr6.eq) goto loc_82333104;'
if body.count(gate) != 1:
    raise RuntimeError('Native keyframed gate changed')
body = body.replace(gate, '\t// Owned H4 keyframed scenery must publish its moving body pose.\n'
                    '\t// Admit motion6 here; retain the following native motion7 rejection.')
prefix = '''// Generated by tools/h4-forge/generate_native_pose_sync.py.
// Native82332FF0 unchanged except its motion6 gate, scoped by the hook below.
// Keep native origin reconstruction, orientation, velocity and notifications.
#include "../generated/default/halo3mp_funcs.78.h"
#include <rex/hook.h>
namespace advanced_forge {
bool OwnsKeyframedSceneryPose(PPCContext&, uint8_t*, uint32_t);
}
extern "C" void __imp__sub_82332FF0(PPCContext& __restrict, uint8_t*);

'''
suffix = '''

REX_HOOK_RAW(sub_82332FF0) {
    if (advanced_forge::OwnsKeyframedSceneryPose(ctx, base, ctx.r3.u32))
        SyncKeyframedScenery(ctx, base);
    else
        __imp__sub_82332FF0(ctx, base);
}
'''
(root / 'halo3mp/src/advanced_forge_pose_sync.cpp').write_text(prefix + body + suffix)
