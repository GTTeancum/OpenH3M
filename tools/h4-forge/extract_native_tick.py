"""Preserve H3 Forge tick with one explicit scenery held-block boundary.

Source extraction only: this does not build or execute either game.
"""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "halo3mp/generated/default/halo3mp_recomp.109.cpp"
OUT = ROOT / "work/h4-forge-research/isolated/native_forge_tick.inl"
NAME = "DEFINE_REX_FUNC(sub_82281A98)"
START = "loc_82281F20:\n"
END = "loc_822821E8:\n"


def main():
    source = SOURCE.read_text()
    begin = source.index(NAME)
    finish = source.find("DEFINE_REX_FUNC(", begin + len(NAME))
    original = source[begin:finish if finish >= 0 else len(source)].rstrip()
    if original.count(START) != 1 or original.count(END) != 1:
        raise ValueError("Native held-block labels changed; inspect original again")
    if original.index(START) >= original.index(END):
        raise ValueError("Native held-block ordering changed")
    # r18 is the original player datum; r31 the resolved held object. Use a
    # context copy: helper calls must not clobber the preserved native suffix.
    # No synthetic PPC return address or host desktop input is involved.
    insertion = (
        "\t// H4 scenery replacement; false preserves the original H3 block.\n"
        "\tif (heldStage) {\n"
        "\t\tauto heldContext = ctx;\n"
        "\t\tif (heldStage(heldContext, base, ctx.r18.u32, ctx.r31.u32))\n"
        "\t\t\tgoto loc_822821E8;\n"
        "\t}\n"
    )
    declaration = (
        "static void RunNativeForgeTick(PPCContext& ctx, uint8_t* base, "
        "bool (*heldStage)(PPCContext&, uint8_t*, uint32_t, uint32_t))"
    )
    body = original.replace(NAME, declaration, 1).replace(START, START + insertion, 1)
    # Enforce that the sole edits are the declaration and insertion. This is
    # an extraction integrity condition, not a behavioral test or parity proof.
    restored = body.replace(declaration, NAME, 1).replace(insertion, "", 1)
    if restored != original:
        raise ValueError("Extraction changed native instructions")
    digest = hashlib.sha256(original.encode()).hexdigest()
    header = (
        "// Generated by tools/h4-forge/extract_native_tick.py; do not hand-edit.\n"
        f"// Original function SHA256 (normalized LF): {digest}\n"
        '// Original82281A98 with a single held-stage dispatch boundary.\n'
        '#include "../../../halo3mp/generated/default/halo3mp_funcs.109.h"\n\n'
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + body + "\n")
    print(f"Extracted original native Forge tick: {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
